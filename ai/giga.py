
from gigachat import GigaChat
import os
import re

from ai.grok import GrokAI

from ai.memory import (
    add_history,
    get_history,
    context
)


class GigaAI:

    def __init__(self):

        # =====================================================
        # GIGACHAT
        # =====================================================

        try:

            key = os.getenv(
                "GIGACHAT_CREDENTIALS"
            )

            if key:

                self.giga = GigaChat(
                    credentials=key,
                    model="GigaChat-2",
                    verify_ssl_certs=False
                )

                print("GigaChat готов")

            else:

                self.giga = None

                print("GigaChat ключ отсутствует")

        except Exception as e:

            print(
                "GigaChat ошибка:",
                e
            )

            self.giga = None


        # =====================================================
        # GROK
        # =====================================================

        try:

            self.grok = GrokAI()

            print("Grok готов")

        except Exception as e:

            print(
                "Grok отключён:",
                e
            )

            self.grok = None


    # =========================================================
    # СИЛЬНО СОКРАЩАЕМ ОТВЕТ
    # =========================================================

    def short_answer(self, answer):

        if not answer:
            return ""

        answer = str(answer).strip()

        # Убираем переносы строк
        answer = re.sub(
            r"\s+",
            " ",
            answer
        ).strip()


        # -----------------------------------------------------
        # Если модель вернула списки/markdown,
        # убираем лишнее форматирование
        # -----------------------------------------------------

        answer = answer.replace(
            "**",
            ""
        )

        answer = answer.replace(
            "__",
            ""
        )


        # -----------------------------------------------------
        # Берём предложения
        # -----------------------------------------------------

        sentences = re.split(
            r"(?<=[.!?…])\s+",
            answer
        )


        sentences = [
            s.strip()
            for s in sentences
            if s.strip()
        ]


        # -----------------------------------------------------
        # Максимум 2 законченных предложения
        # -----------------------------------------------------

        if len(sentences) >= 2:

            answer = (
                sentences[0]
                + " "
                + sentences[1]
            )

        elif len(sentences) == 1:

            answer = sentences[0]

        else:

            answer = answer


        # -----------------------------------------------------
        # Дополнительная защита.
        #
        # Если два предложения всё равно огромные,
        # берём только первое законченное предложение.
        # -----------------------------------------------------

        if len(answer) > 450:

            first = re.split(
                r"(?<=[.!?…])\s+",
                answer
            )[0]

            if first:

                answer = first


        return answer.strip()


    # =========================================================
    # AI
    # =========================================================

    def ask(self, text):

        add_history(
            "user",
            text
        )


        # =====================================================
        # SYSTEM PROMPT
        # =====================================================

        system_prompt = """
Ты JARVIS — голосовой помощник.

ТВОЯ ГЛАВНАЯ ЗАДАЧА — ОТВЕЧАТЬ ОЧЕНЬ КОРОТКО.

Строгие правила:

- Максимум 2 предложения.
- Желательно 1 предложение.
- Не более 300 символов.
- Не пиши длинные объяснения.
- Не используй списки.
- Не используй Markdown.
- Не повторяй вопрос пользователя.
- Не добавляй вступление.
- Не добавляй заключение.
- Не пиши "конечно", "разумеется" и подобные лишние слова,
  если они не нужны.
- Всегда полностью заканчивай мысль.
- Никогда не обрывай предложение.
- Никогда не обрывай слово.
- Ответ предназначен для голосового помощника.

Пример:

Пользователь: Как дела?
JARVIS: Всё отлично, готов работать.

Пользователь: Что такое процессор?
JARVIS: Процессор — это главный вычислительный компонент компьютера.

Пользователь: Расскажи подробнее.
JARVIS: Процессор выполняет команды программ и обрабатывает данные.

Даже если вопрос сложный, сначала дай короткий ответ.
"""


        # =====================================================
        # СООБЩЕНИЯ
        # =====================================================

        messages = [

            {
                "role": "system",
                "content":
                    system_prompt
                    + "\n\n"
                    + context()
            }

        ]


        # =====================================================
        # ИСТОРИЯ
        # =====================================================

        history = get_history()

        # Не отправляем бесконечную историю
        # Последние 10 сообщений достаточно для JARVIS.

        for item in history[-10:]:

            messages.append({

                "role": item["role"],
                "content": item["content"]

            })


        # =====================================================
        # GIGACHAT
        # =====================================================

        if self.giga:

            try:

                response = self.giga.chat({

                    "messages": messages

                })


                answer = response.choices[0].message.content


                # Жёстко сокращаем результат
                answer = self.short_answer(
                    answer
                )


                add_history(
                    "assistant",
                    answer
                )


                print(
                    "Ответ: GigaChat"
                )

                print(
                    f"JARVIS: {answer}"
                )


                return answer


            except Exception as e:

                print(
                    "GigaChat недоступен:",
                    e
                )


        # =====================================================
        # GROK
        # =====================================================

        if self.grok:

            try:

                answer = self.grok.ask(
                    text
                )


                answer = self.short_answer(
                    answer
                )


                add_history(
                    "assistant",
                    answer
                )


                print(
                    "Ответ: Grok"
                )


                return answer


            except Exception as e:

                print(
                    "Grok ошибка:",
                    e
                )


        # =====================================================
        # НЕТ AI
        # =====================================================

        return "Все системы ИИ недоступны"
